import assert from 'node:assert/strict';
import {createEngine} from './engine.mjs';
const engine=createEngine();
const host=engine.run('create',{scope:['m21']},'teacher');
const student=engine.run('join',{code:host.code},'student');
assert.throws(()=>engine.run('start',{token:host.token},'student'),/계정/);
engine.run('start',{token:host.token},'teacher');
const restored=createEngine(JSON.parse(JSON.stringify(engine.dump())));
const q=restored.run('question',{token:student.token},'student');
assert.equal(typeof q.answer,'undefined');
const request={token:student.token,questionId:q.id,requestId:crypto.randomUUID(),answer:q.a*q.b,remainder:0};
const first=restored.run('answer',request,'student');
assert.equal(first.correct,true);
const again=createEngine(restored.dump()).run('answer',request,'student');
assert.equal(again.hp,first.hp);
const deleted=createEngine(restored.dump());
deleted.run('end',{token:host.token},'teacher');
assert.equal(deleted.dump().rooms.length,0);
assert.equal(deleted.dump().sessions.length,0);
console.log('PASS: cloud room restoration, account isolation, hidden answers, idempotency, deletion');
